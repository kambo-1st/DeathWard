#!/usr/bin/env python3
"""Extract the heart-placement layer of pinned Basement normal-room templates.

Room selection, other actors/grid, eligibility and source seed mapping are not
reproduced by extracting this layer. No game install writes or sprite imports.
"""
import argparse,hashlib,json,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'reference/isaac-repentance-1.7.9b/extracted/repentance/resources-dlc3/rooms/01.basement.stb'
OUT=ROOT/'docs/reports/isaac-first-floor-parity/d09a-room-hearts'
SHA='524406fcb10c6275995292c0bd024cfc43d3d30c32b233e55d4d514573d963b0'
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    data=SOURCE.read_bytes();assert hashlib.sha256(data).hexdigest()==SHA
    magic,count=struct.unpack_from('<4sI',data);assert magic==b'STB1';offset=8;pool=[];rock_room=[];combat_room=[]
    def take(fmt):
        nonlocal offset
        result=struct.unpack_from(fmt,data,offset);offset+=struct.calcsize(fmt);return result
    for index in range(count):
        kind,variant,subtype,difficulty,n=take('<IIIBH');offset+=n
        weight,width,height,shape,doors,stacks=take('<fBBBBH')
        door_mask=0
        for _ in range(doors):
            x,y,exists=take('<hh?')
            if shape==1 and exists:
                # Ordinary 13x7 source door slots: left/up/right/down.
                door_mask|=1<<{(-1,3):0,(6,-1):1,(13,3):2,(6,7):3}[(x,y)]
        slots=[]
        for ordinal in range(stacks):
            x,y,entries=take('<hhB')
            choices=[dict(zip(('type','variant','subtype','weight'),take('<HHHf'))) for _ in range(entries)]
            if (kind,variant,subtype)==(1,91,0):rock_room.append(dict(x=x,y=y,choices=choices))
            if (kind,variant,subtype)==(1,4,0):combat_room.append(dict(x=x,y=y,choices=choices))
            # Preserve competing non-heart choices in mixed stacks; never
            # renormalize a bomb/sack/etc. into an extra heart.
            if any(c['type']==5 and c['variant']==10 for c in choices):slots.append(dict(ordinal=ordinal,x=x,y=y,choices=choices))
        if kind==1 and weight>0 and 1<=difficulty<=5 and shape==1 and (width,height)==(13,7):
            pool.append(dict(index=index,type=kind,variant=variant,subtype=subtype,difficulty=difficulty,shape=shape,doors=door_mask,weight=weight,spawnCount=stacks,slots=slots))
    assert offset==len(data)
    assert len(pool)==433
    entries=[];slots=[];layouts=[]
    for r in pool:
        layouts.append((r['type'],r['variant'],r['subtype'],r['difficulty'],r['shape'],r['doors'],r['weight'],len(slots),len(r['slots']),r['spawnCount']))
        for slot in r['slots']:
            slots.append((slot['x'],slot['y'],len(entries),len(slot['choices']),slot['ordinal']))
            entries.extend((c['type'],c['variant'],c['subtype'],c['weight']) for c in slot['choices'])
    header='''// Generated by scripts/isaac-reference/extract-room-heart-layouts.py; do not hand edit.
#pragma once
#include <array>
namespace dw {
struct SourceRoomHeartLayout {int type,variant,subtype,difficulty,shape,doors;float weight;int firstSlot,slotCount,spawnCount;};
struct SourceRoomHeartSlot {int x,y,firstChoice,choiceCount,ordinal;};
struct SourceRoomHeartChoice {int type,variant,subtype;float weight;};
'''
    for typ,name,rows in [('SourceRoomHeartLayout','BasementHeartLayouts',layouts),('SourceRoomHeartSlot','BasementHeartSlots',slots),('SourceRoomHeartChoice','BasementHeartChoices',entries)]:
        header+=f'inline constexpr std::array<{typ},{len(rows)}> {name}{{{{\n'
        for row in rows:header+='    {'+','.join(str(x) if isinstance(x,int) else format(x,'.9g')+'f' if '.' in format(x,'.9g') else format(x,'.9g')+'.f' for x in row)+'},\n'
        header+='}};\n'
    header+='} // namespace dw\n'
    manifest=dict(source=str(SOURCE.relative_to(ROOT)),sha256=SHA,target='Installed Repentance 1.7.9b',filter='type1, positive weight, difficulty1-5, shape1, 13x7; includes templates with zero heart slots',template_count=len(pool),heart_slot_count=len(slots),choice_count=len(entries),scope='Heart layer only. The main-game adapter uses the verified native numeric/weighted selector and spawn-slot sequence with DW door/difficulty/seed inputs. Native caller/floor selection, full actors/grid, unlock filters and descriptor RNG are not certified.',templates=pool)
    rocks=[(s['x'],s['y']) for s in rock_room if s['choices']==[dict(type=1000,variant=0,subtype=0,weight=1.0)]]
    assert len(rock_room)==21 and len(rocks)==19
    assert [s for s in rock_room if (s['x'],s['y']) not in rocks]==[dict(x=x,y=3,choices=[dict(type=5,variant=10,subtype=0,weight=1.0)]) for x in (5,7)]
    rock_header='// Generated by scripts/isaac-reference/extract-room-heart-layouts.py.\n#pragma once\n#include <array>\nnamespace dw {\ninline constexpr std::array<std::array<int,2>,19> Basement91Rocks{{\n'
    rock_header+=''.join(f'    {{{x},{y}}},\n' for x,y in rocks)+'}};\n} // namespace dw\n'
    rock_manifest=dict(source=str(SOURCE.relative_to(ROOT)),sha256=SHA,template='1.91.0',slots=rock_room,rock_count=19,heart_slots=2,enemies=0,scope='Complete source content record. Native runtime grid substitution, drops and physical collision remain separate verification.')
    combat_rocks=[(s['x'],s['y']) for s in combat_room if s['choices']==[dict(type=1000,variant=0,subtype=0,weight=1.0)]]
    gapers=[(s['x'],s['y']) for s in combat_room if s['choices']==[dict(type=10,variant=1,subtype=0,weight=1.0)]]
    assert len(combat_room)==19 and len(combat_rocks)==17 and gapers==[(10,1),(2,5)]
    combat_header='// Generated by scripts/isaac-reference/extract-room-heart-layouts.py.\n#pragma once\n#include <array>\nnamespace dw {\n'
    for name,rows in [('Basement4Rocks',combat_rocks),('Basement4Gapers',gapers)]:
        combat_header+=f'inline constexpr std::array<std::array<int,2>,{len(rows)}> {name}{{{{\n'
        combat_header+=''.join(f'    {{{x},{y}}},\n' for x,y in rows)+'}};\n'
    combat_header+='} // namespace dw\n'
    metadata=next(r for r in pool if (r['type'],r['variant'],r['subtype'])==(1,4,0))
    combat_manifest=dict(source=str(SOURCE.relative_to(ROOT)),sha256=SHA,template='1.4.0',metadata=metadata,slots=combat_room,rock_count=17,gapers=2,pickups=0,scope='Complete source content record. Canyon size, shape and connections are retained; native runtime grid substitution, actor AI, drops and physics are separate verification.')
    for path,content in [(OUT/'source-layouts.json',json.dumps(manifest,indent=2)+'\n'),(ROOT/'src/world/SourceRoomHeartsData.hpp',header),(ROOT/'src/world/SourceHeartRockRoomData.hpp',rock_header),(OUT.parent/'native-heart-rock-room/source-room.json',json.dumps(rock_manifest,indent=2)+'\n'),(ROOT/'src/world/SourceCombatRockRoomData.hpp',combat_header),(OUT.parent/'native-combat-rock-room/source-room.json',json.dumps(combat_manifest,indent=2)+'\n')]:
        if args.check:assert path.read_text()==content,path
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    print(f'PASS {len(pool)} templates including empty heart layers, {len(slots)} heart stacks and {len(entries)} weighted choices')
if __name__=='__main__':main()
