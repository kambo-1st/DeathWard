// Optional offline viewer check. Set module/browser paths for an existing Playwright installation.
const { chromium } = require(process.env.ISAAC_REFERENCE_PLAYWRIGHT || 'playwright');
const path = require('path');
const { pathToFileURL } = require('url');
const rootDir = path.resolve(__dirname, '../..');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({headless:true, ...(process.env.ISAAC_REFERENCE_CHROMIUM ? { executablePath:process.env.ISAAC_REFERENCE_CHROMIUM } : {}),args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];const remote=[];page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(r.url().startsWith('http'))remote.push(r.url())});
 const root=pathToFileURL(path.join(rootDir,'docs/reports/isaac-mechanics-reference-2026-10-25.html')).href;
 const captures=path.join(rootDir,'artifacts/isaac-reference');
 fs.mkdirSync(captures,{recursive:true});
 await page.goto(root);await page.locator('h2').waitFor();
 await page.screenshot({path:path.join(captures,'overview.png')});
 await page.locator('aside [data-action="catalog"]').click();
 await page.locator('#query').fill('Mother');
 await page.locator('[data-action="record"][data-value="entity:912.0.0"]').click();
 if(!await page.locator('h2').textContent().then(x=>x==='Mother'))throw Error('Mother not found by public name');
 await page.screenshot({path:path.join(captures,'mother.png')});
 await page.locator('[data-action="catalog"]').first().click();
 await page.locator('#query').fill('10.1.0');
 await page.locator('[data-action="record"][data-value="entity:10.1.0"]').click();
 if(!await page.locator('main').textContent().then(x=>x.includes('50%')&&x.includes('Configured health')))throw Error('Gaper detail missing');
 await page.locator('aside [data-action="catalog"]').click();
 await page.locator('[data-action="filter"][data-value="pill"]').click();
 await page.locator('#query').fill('Bombs');
 await page.locator('[data-action="record"][data-value="pill:3"]').click();
 if(!await page.locator('main').textContent().then(x=>x.includes('50%')))throw Error('Horse pill text missing');
 await page.locator('aside [data-action="interactions"]').click();
 await page.locator('#query').fill('Soy Milk');
 if(await page.locator('#results .card').count()<5)throw Error('Interaction search failed');
 await page.locator('aside [data-action="coverage"]').click();
 if(!await page.locator('main').textContent().then(x=>x.includes('Frozen Enemy')))throw Error('Unknown NPCs missing');
 await page.locator('aside [data-action="sources"]').click();
 await page.locator('aside [data-action="chapter"][data-value="porting"]').click();
 if(!await page.locator('main').textContent().then(x=>x.includes('9,130,000')))throw Error('ID collision spec missing');
 await page.locator('aside [data-action="catalog"]').click();
 await page.locator('[data-action="filter"][data-value="collectible"]').click();
 await page.locator('[data-action="page"]').last().click();
 if(!await page.locator('#results').textContent().then(x=>x.includes('Page 2')))throw Error('Pagination failed');
 await page.setViewportSize({width:390,height:844});
 await page.locator('aside [data-action="overview"]').click();
 await page.screenshot({path:path.join(captures,'mobile.png')});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(errors.length||remote.length||overflow)throw Error(JSON.stringify({errors,remote,overflow}));
 await browser.close();
 const result={status:'passed',browser:'Chromium headless; local file://',checks:['offline load','public enemy name lookup','Gaper behavior and HP','normal/horse pill details','interaction search','coverage and unknowns','source manifest','implementation chapter','catalog pagination','390px viewport without horizontal overflow'],javascript_errors:errors,network_requests:remote};
 fs.writeFileSync(path.join(rootDir,'docs/research/isaac-mechanics-browser-validation.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exit(1)});
