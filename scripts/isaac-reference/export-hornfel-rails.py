#!/usr/bin/env python3
"""Extract only authored track facts; never infer ordinary pool eligibility."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/reports/isaac-enemy-port/ordnance/hornfel-room-templates.json"
OUTPUT = ROOT / "assets/mechanics/rails.mechanics"
REPORT = ROOT / "docs/reports/isaac-enemy-port/hornfel_controller/rail-source.json"


def main():
    records = json.loads(SOURCE.read_text())["matches"]
    lines = ["DEATHWARD_MECHANICS 1", "# Installed Repentance 1.7.9b rail coordinates; regenerated by export-hornfel-rails.py.",
             "# These are geometry definitions, not ordinary NPC/boss pool entries.",
             "# Variant ports: 0 EW,1 NS,2 ES,3 WS,4 EN,5 WN,6 NESW,7 E,8 W,9 S,10 N.",
             "# Crossing-straight and stop-reversal are explicit local routing policies.",
             "# rail_layout key width height; rail_cell key x z variant over_pit"]
    manifest = []
    for room in records:
        rails = [s for s in room["spawns"] if s["type"] in (6000, 6001)]
        if not rails:
            continue
        family = "void" if "void.stb" in room["path"] else "special"
        key = f"hornfel_{family}_{room['variant']}"
        lines += ["", f"# {Path(room['path']).name}, index {room['index']}, {room['name'] or 'unnamed'}, shape {room['shape']}",
                  f"rail_layout {key} {room['width']} {room['height']}"]
        closed = 0
        for x, z, enabled in room["doors"]:
            if not enabled:
                side = 0 if z < 0 else 1 if x >= room["width"] else 2 if z >= room["height"] else 3
                closed |= 1 << side
        lines.append(f"rail_closed_entrances {key} {closed}")
        for cell in sorted(rails, key=lambda s: (s["y"], s["x"])):
            assert cell["subtype"] == 0 and cell["weight"] == 1, "Randomized rail cell needs explicit policy"
            lines.append(f"rail_cell {key} {cell['x']} {cell['y']} {cell['variant']} {int(cell['type'] == 6001)}")
        for cell in sorted(room["spawns"], key=lambda s: (s["y"], s["x"])):
            if cell["type"] in (3000, 1000):
                command = "rail_pit" if cell["type"] == 3000 else "rail_rock"
                assert cell["weight"] == 1
                lines.append(f"{command} {key} {cell['x']} {cell['y']}")
        manifest.append({"key": key, "source": room["path"], "source_sha256": room["sha256"],
                         "source_index": room["index"], "variant": room["variant"], "shape": room["shape"],
                         "size": [room["width"], room["height"]], "name": room["name"], "closed_entrances": closed,
                         "tiles": len(rails), "pit_tiles": sum(c["type"] == 6001 for c in rails),
                         "additional_pits": sum(c["type"] == 3000 for c in room["spawns"]),
                         "rocks": sum(c["type"] == 1000 for c in room["spawns"]),
                         "source_room_weight": room["weight"], "ordinary_pool_enabled": False,
                         "category": "void" if family == "void" else "double_trouble" if "Double Trouble" in room["name"] else "normal"})
    OUTPUT.write_text("\n".join(lines) + "\n")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps({"baseline": "Repentance 1.7.9b", "source": str(SOURCE.relative_to(ROOT)),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(), "output": str(OUTPUT.relative_to(ROOT)),
        "output_sha256": hashlib.sha256(OUTPUT.read_bytes()).hexdigest(), "templates": manifest,
        "limits": ["This exports tracks, pit-rail flags, ordinary pits and rock cells. Other room objects remain in the preserved STB extraction.",
                   "The Mines placeholder contains no tracks and is not fabricated into a layout.",
                   "Source room weights are recorded, not interpreted as native runtime selection probabilities.",
                   "The old preflight's vertical end-stop mapping is corrected: 9 has S, 10 has N. All installed tile ports now have reciprocal neighbors.",
                   "Straight crossings and reversing at a stop are local traversal policies, not recovered native control flow."]}, indent=2) + "\n")
    print(f"Exported {len(manifest)} layouts, {sum(m['tiles'] for m in manifest)} rail cells")


if __name__ == "__main__":
    main()
