"""Bold angular punctuation in the same 1000-cap coordinate system."""
from shapely.affinity import rotate, scale, translate
from shapely.geometry import Polygon, box
from shapely.ops import unary_union


def symbols(letter_shapes):
    p = {}
    dot = Polygon([(0, 0), (180, 5), (195, 165), (20, 180)])
    comma = Polygon([(0, 170), (200, 180), (190, 15), (65, -165),
                     (-15, -125), (65, 5), (0, 10)])
    quote = Polygon([(0, 1000), (180, 1010), (165, 830), (55, 710), (0, 760)])
    p['.'], p[','], p["'"] = dot, comma, quote
    p[':'] = unary_union([dot, translate(dot, yoff=515)])
    p[';'] = unary_union([comma, translate(dot, yoff=515)])
    p['"'] = unary_union([quote, translate(quote, xoff=310)])
    p['!'] = unary_union([dot, Polygon([(15, 330), (190, 340), (240, 990), (0, 1000)])])
    p['?'] = unary_union([translate(dot, xoff=220), Polygon([
        (0, 700), (10, 840), (120, 980), (460, 1000), (650, 900),
        (650, 660), (420, 445), (400, 325), (210, 325), (205, 555),
        (430, 735), (425, 810), (220, 825), (205, 690)])])
    p['-'] = Polygon([(0, 420), (620, 450), (640, 600), (15, 615)])
    p['_'] = box(0, -180, 800, -15)
    p['/'] = Polygon([(0, -50), (180, -65), (680, 1030), (505, 1050)])
    p['\\'] = scale(p['/'], xfact=-1, yfact=1, origin=(340, 0))
    p['|'] = Polygon([(0, -120), (185, -100), (165, 1050), (5, 1030)])
    p['('] = Polygon([(280, 1030), (80, 900), (0, 540), (50, 130),
                      (250, -80), (370, 20), (230, 220), (190, 570),
                      (240, 840), (380, 970)])
    p[')'] = scale(p['('], xfact=-1, yfact=1, origin=(190, 0))
    p['['] = Polygon([(0, -100), (365, -100), (365, 70), (175, 70),
                      (175, 870), (365, 870), (365, 1040), (0, 1040)])
    p[']'] = scale(p['['], xfact=-1, yfact=1, origin=(182.5, 0))
    p['{'] = Polygon([(440, 1040), (190, 1040), (90, 905), (110, 650),
                      (0, 560), (0, 400), (110, 300), (90, 25),
                      (190, -100), (440, -100), (440, 80), (290, 100),
                      (300, 350), (200, 480), (300, 610), (290, 845), (440, 865)])
    p['}'] = scale(p['{'], xfact=-1, yfact=1, origin=(220, 0))
    p['+'] = unary_union([box(0, 410, 700, 590), box(260, 150, 440, 850)])
    p['='] = unary_union([box(0, 250, 690, 415), box(10, 610, 700, 775)])
    p['<'] = Polygon([(550, 900), (650, 730), (225, 500),
                      (650, 265), (550, 100), (0, 420), (0, 590)])
    p['>'] = scale(p['<'], xfact=-1, yfact=1, origin=(325, 0))
    p['^'] = Polygon([(0, 700), (200, 1000), (390, 1000),
                      (610, 700), (400, 700), (300, 850), (190, 700)])
    p['`'] = Polygon([(0, 1000), (215, 1000), (395, 740), (205, 750)])
    p['~'] = Polygon([(0, 475), (140, 650), (295, 670), (520, 565),
                      (650, 680), (760, 555), (620, 390), (470, 375),
                      (245, 480), (110, 365)])
    arm = box(265, 455, 420, 1040)
    p['*'] = unary_union([rotate(arm, a, origin=(342.5, 747.5)) for a in [0, 60, 120]])
    p['#'] = unary_union([
        Polygon([(60, 0), (235, 0), (445, 1000), (260, 1000)]),
        Polygon([(430, 0), (600, 0), (805, 1000), (625, 1000)]),
        box(0, 260, 800, 435), box(70, 640, 870, 805)])
    p['$'] = unary_union([scale(letter_shapes['S'], xfact=.7, yfact=1, origin=(0, 0)),
                          box(290, -110, 410, 1100)])
    ring = Polygon([(30, 0), (270, 0), (300, 70), (280, 360), (30, 380), (0, 310)],
                   [[(100, 100), (200, 100), (195, 275), (105, 280)]])
    p['%'] = unary_union([translate(ring, yoff=620), translate(ring, xoff=600),
                          Polygon([(105, 0), (290, 0), (810, 1000), (630, 1000)])])
    p['&'] = Polygon([(0, 200), (40, 450), (210, 620), (80, 770),
                      (90, 920), (220, 1000), (530, 1000), (670, 880),
                      (620, 700), (440, 560), (550, 400), (650, 590),
                      (850, 500), (705, 255), (850, 45), (640, 0),
                      (555, 120), (400, 0), (125, 0)],
                     [[(220, 200), (415, 230), (290, 420)],
                      [(285, 720), (455, 825), (300, 835)]])
    outer_c = Polygon([(160, 0), (0, 150), (0, 835), (170, 1000),
                       (835, 980), (1000, 825), (985, 240), (800, 120),
                       (800, 290), (850, 330), (850, 800), (730, 845),
                       (230, 850), (150, 780), (150, 210), (250, 140),
                       (765, 160), (790, 0)])
    inner = Polygon([(250, 300), (265, 685), (375, 755), (705, 740),
                     (735, 285), (850, 290), (850, 120), (615, 130),
                     (555, 235), (330, 220)],
                    [[(415, 390), (550, 395), (550, 590), (420, 585)]])
    p['@'] = unary_union([outer_c, inner])
    assert len(p) == 32
    for ch, shape in p.items():
        assert shape.is_valid and not shape.is_empty, (ch, 'invalid punctuation guide')
    return p


